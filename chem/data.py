class MoleculeDataset(InMemoryDataset):
    """
    从 CSV 读取 SMILES（和可选标签）并转换为 PyG Data 的 InMemoryDataset 实现。
    """
    def __init__(
        self,
        root: str,
        dataset=None,
        transform=None,
        pre_transform=None,
        pre_filter=None,
        empty=False,
    ):
        self.dataset = dataset
        self.root = root

        super(MoleculeDataset, self).__init__(root, transform, pre_transform,
                                                 pre_filter)
        self.transform, self.pre_transform, self.pre_filter = transform, pre_transform, pre_filter

        if not empty:
            # 兼容 PyTorch 2.6+ 默认 weights_only=True 的变化
            # 优先禁用 weights_only；若老版本不支持该参数则回退；
            # 若仍失败，则允许 DataEdgeAttr 作为安全全局再尝试。
            try:
                self.data, self.slices = torch.load(self.processed_paths[0], weights_only=False)
            except TypeError:
                # 旧版 torch 无 weights_only 参数
                self.data, self.slices = torch.load(self.processed_paths[0])
            except pickle.UnpicklingError:
                try:
                    from torch.serialization import add_safe_globals
                    # 有些 PyG 版本定义在 torch_geometric.data.data
                    try:
                        from torch_geometric.data.data import DataEdgeAttr
                        add_safe_globals([DataEdgeAttr])
                    except Exception:
                        # 兼容不同路径或缺失该类的情况；若失败也继续尝试加载
                        pass
                except Exception:
                    pass
                # 再次尝试禁用 weights_only 加载
                self.data, self.slices = torch.load(self.processed_paths[0], weights_only=False)


    @property
    def raw_file_names(self):
        """
        返回期望存在于 raw 目录下的原始文件名。
        - 若传入 dataset 含扩展名，则按原样使用，例如 'test.csv'。
        - 常见数据集名会映射到约定文件名：
          * 'zinc_standard_agent' -> 'zinc_standard_agent.csv.gz'
          * 其他（如 'hiv', 'test'）-> f'{name}.csv'
        """
        name = os.path.basename(self.dataset) if self.dataset else 'data.csv'
        # 已带扩展名，直接返回
        if '.' in name:
            return [name]
        # 特例：zinc 标准数据集使用 gzip 压缩
        if name == 'zinc_standard_agent':
            return ['zinc_standard_agent.csv.gz']
        # 默认按 csv 处理
        return [f'{name}.csv']

    @property
    def processed_file_names(self):
        return ["data.pt"]

    def download(self):
        # 本地数据集，不需要下载
        pass

    def process(self):
        data_smiles_list = []
        data_list = []

        if self.dataset == 'zinc':
            input_path = self.raw_paths[0]
            input_df = pd.read_csv(input_path,
                                   dtype='str')
            smiles_list = list(input_df['smiles'])
            zinc_id_list = list(input_df['zinc_id'])
            for i in range(len(smiles_list)):
                print(i)
                s = smiles_list[i]
                # each example contains a single species
                try:
                    rdkit_mol = AllChem.MolFromSmiles(s)
                    if rdkit_mol != None:  # ignore invalid mol objects
                        # # convert aromatic bonds to double bonds
                        # Chem.SanitizeMol(rdkit_mol,
                        #                  sanitizeOps=Chem.SanitizeFlags.SANITIZE_KEKULIZE)
                        data = mol_to_graph(rdkit_mol)
                        # manually add mol id
                        id = int(zinc_id_list[i].split('ZINC')[1].lstrip('0'))
                        data.id = torch.tensor(
                            [id])  # id here is zinc id value, stripped of
                        # leading zeros
                        data_list.append(data)
                        data_smiles_list.append(smiles_list[i])
                except:
                    continue
        elif self.dataset == 'hiv':
            smiles_list, rdkit_mol_objs, labels = \
                _load_hiv_dataset(self.raw_paths[0])
            for i in range(len(smiles_list)):
                print(i)
                rdkit_mol = rdkit_mol_objs[i]
                if rdkit_mol is None:
                    # 无效 SMILES，跳过
                    continue
                # # convert aromatic bonds to double bonds
                # Chem.SanitizeMol(rdkit_mol,
                #                  sanitizeOps=Chem.SanitizeFlags.SANITIZE_KEKULIZE)
                data = mol_to_graph(rdkit_mol)
                if data is None:
                    continue
                # manually add mol id
                data.id = torch.tensor(
                    [i])  # id here is the index of the mol in
                # the dataset
                data.y = torch.tensor([labels[i]])
                data_list.append(data)
                data_smiles_list.append(smiles_list[i])

        elif self.dataset == 'jcesr':
            smiles_list, rdkit_mol_objs, labels = \
                _load_jcesr_dataset(self.raw_paths[0])
            for i in range(len(smiles_list)):
                print(i)
                rdkit_mol = rdkit_mol_objs[i]
                if rdkit_mol is None:
                    continue
                # # convert aromatic bonds to double bonds
                # Chem.SanitizeMol(rdkit_mol,
                #                  sanitizeOps=Chem.SanitizeFlags.SANITIZE_KEKULIZE)
                data = mol_to_graph(rdkit_mol)
                if data is None:
                    continue
                # manually add mol id
                data.id = torch.tensor(
                    [i])  # id here is the index of the mol in
                # the dataset
                data.y = torch.tensor([labels[i]])
                data_list.append(data)
                data_smiles_list.append(smiles_list[i])                
                
        elif self.dataset == 'bace':
            smiles_list, rdkit_mol_objs, folds, labels = \
                _load_bace_dataset(self.raw_paths[0])
            for i in range(len(smiles_list)):
                print(i)
                rdkit_mol = rdkit_mol_objs[i]
                if rdkit_mol is None:
                    # BACE 原始 CSV 中可能含有无效 SMILES
                    continue
                # # convert aromatic bonds to double bonds
                # Chem.SanitizeMol(rdkit_mol,
                #                  sanitizeOps=Chem.SanitizeFlags.SANITIZE_KEKULIZE)
                data = mol_to_graph(rdkit_mol)
                if data is None:
                    continue
                # manually add mol id
                data.id = torch.tensor(
                    [i])  # id here is the index of the mol in
                # the dataset
                data.y = torch.tensor([labels[i]])
                data.fold = torch.tensor([folds[i]])
                data_list.append(data)
                data_smiles_list.append(smiles_list[i])

        elif self.dataset == 'test':
            smiles_list, rdkit_mol_objs, labels = \
                _load_test_dataset(self.raw_paths[0])
            for i in range(len(smiles_list)):
                print(i)
                rdkit_mol = rdkit_mol_objs[i]
                if rdkit_mol is None:
                    continue
                # # convert aromatic bonds to double bonds
                # Chem.SanitizeMol(rdkit_mol,
                #                  sanitizeOps=Chem.SanitizeFlags.SANITIZE_KEKULIZE)
                data = mol_to_graph(rdkit_mol)
                if data is None:
                    continue
                # manually add mol id
                data.id = torch.tensor(
                    [i])  # id here is the index of the mol in
                # the dataset
                data.y = torch.tensor([labels[i]])
                data_list.append(data)
                data_smiles_list.append(smiles_list[i])
        else:
            raise ValueError('Invalid dataset name')
        # 若全部被过滤，给出清晰错误提示
        if len(data_list) == 0:
            raise ValueError(f"No valid molecules were found for dataset '{self.dataset}'. "
                             f"Please check the raw CSV at: {self.raw_paths[0]}")

        # 保存到标准 processed 目录和文件，便于 InMemoryDataset 直接加载
        os.makedirs(self.processed_dir, exist_ok=True)
        pd.Series(data_smiles_list).to_csv(
            os.path.join(self.processed_dir, 'smiles.csv'),
            index=False,
            header=False,
        )
        data, slices = self.collate(data_list)
        torch.save((data, slices), self.processed_paths[0])